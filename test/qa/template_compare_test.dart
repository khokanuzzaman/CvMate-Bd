/// Host side of the simulator template QA (docs/qa/templates/compare/).
/// Reads what `integration_test/template_compare_test.dart` saved (preview
/// pages as the device rendered them, the exported PDFs, screenshots), checks
/// preview against PDF, and writes the side-by-side images and RESULTS.md.
/// Runs only when TEMPLATE_QA_DIR is set:
///
///   TEMPLATE_QA_DIR=build/qa TEMPLATE_QA_DEVICE="iPhone 17 Pro, iOS 26.5" \
///     TEMPLATE_QA_IMAGE_BASE=<url of the images branch folder> \
///     flutter test test/qa/template_compare_test.dart
void main() {
  final source = Platform.environment['TEMPLATE_QA_DIR'];
  final device = Platform.environment['TEMPLATE_QA_DEVICE'] ?? 'simulator';
  // Where RESULTS.md links the images (they are kept off main).
  final images = Platform.environment['TEMPLATE_QA_IMAGE_BASE'] ?? '.';
  final out = Directory('docs/qa/templates/compare');
  final skip = source == null || !Poppler.canRaster;
  final rows = <String>[];

  tearDownAll(() {
    if (rows.isEmpty) {
      return;
    }
    out.createSync(recursive: true);
    File('${out.path}/RESULTS.md').writeAsStringSync(
      [
        '# Preview vs PDF on the simulator ($device)',
        '',
        'Generated by `test/qa/template_compare_test.dart` from the run of',
        '`integration_test/template_compare_test.dart`. Left of each image: the',
        'preview screen on the device; right: page 1 of the PDF the app',
        'exported, drawn by macOS Quick Look.',
        '',
        '| Template | Fixture | Identity | Pages | Layout per page | Same PDF as export | iOS vs macOS page 1 (info) | All text in PDF | Result |',
        '|---|---|---|---|---|---|---|---|---|',
        ...rows,
        '',
      ].join('\n'),
    );
  });

  for (final fixture in [TemplateFixture.full, TemplateFixture.nonAscii]) {
    for (final template in CvTemplate.values) {
      final name = '${fixture.name}-${template.name}';
      test(name, skip: skip, () {
        final dir = '$source/templates';
        final pdf = File('$dir/$name-export.pdf');
        final previewPdf = File('$dir/$name-preview.pdf');
        final preview = [
          for (var i = 1; File('$dir/$name-preview-p$i.png').existsSync(); i++)
            File('$dir/$name-preview-p$i.png').readAsBytesSync(),
        ];
        expect(pdf.existsSync(), isTrue, reason: pdf.path);
        expect(preview, isNotEmpty, reason: 'preview pages of $name');

        final width = Poppler.pageWidth(pdf);
        TemplateLook look(Uint8List png) => lookOf(png, pageWidthPt: width);
        final exported = Poppler.raster(pdf, dpi: cvPreviewDpi);
        // Quick Look and iOS round the page height differently (1754 vs
        // 1753 px); scale Quick Look's page to the device's size so the
        // comparison is not thrown off by a growing sub-pixel drift.
        final device = decodePage(preview.first);
        final quickLook = img.encodePng(
          img.copyResize(
            decodePage(_quickLook(pdf)),
            width: device.width,
            height: device.height,
            interpolation: img.Interpolation.average,
          ),
        );

        final identity = look(preview.first).template == template;
        final pages = preview.length == exported.length;
        // Page 1 against Quick Look (Apple's renderer, same fonts as iOS);
        // later pages against poppler, which substitutes Helvetica, so only
        // their rules, photo and whether there are dark bars.
        final layout =
            pages &&
            _sameLayout(look(preview.first), look(quickLook)) &&
            [
              for (var i = 1; i < preview.length; i++)
                _sameRules(look(preview[i]), look(exported[i])),
            ].every((same) => same);
        // Same content: one renderer draws the preview's PDF and the exported
        // PDF alike (the files differ only in their creation time).
        final samePdf = differingPixels(
          _quickLook(previewPdf),
          _quickLook(pdf),
        );
        // iOS against macOS: Helvetica is not embedded, so each system draws
        // it with its own copy; glyph widths differ a little. Reported only.
        final pixels = differingPixels(preview.first, quickLook);
        final text = Poppler.collapse(
          Poppler.text(pdf).replaceAll(RegExp(r'Page \d+ of \d+'), ' '),
        ).toLowerCase();
        final missing = [
          for (final value in fixtureCv(fixture, template).expected)
            if (!text.contains(value.replaceAll('🚀', '').trim().toLowerCase()))
              value,
        ];
        final pass =
            identity && pages && layout && samePdf < 0.001 && missing.isEmpty;

        String mark(bool ok) => ok ? 'PASS' : 'FAIL';
        rows.add(
          '| ${template.label} | ${fixture == TemplateFixture.full ? '(a) full' : '(c) Bangla'} '
          '| ${mark(identity)} '
          '| ${mark(pages)} (${preview.length} / ${exported.length}) '
          '| ${mark(layout)} '
          '| ${mark(samePdf < 0.001)} (${_percent(samePdf)}) '
          '| ${_percent(pixels)} '
          '| ${mark(missing.isEmpty)}${missing.isEmpty ? '' : ' (missing: ${missing.join(', ')})'} '
          '| **${mark(pass)}** [image]($images/$name.png) |',
        );

        _sideBySide(
          File(_screenshot(source!, name)).readAsBytesSync(),
          quickLook,
          File('${out.path}/$name.png'),
        );

        expect(identity, isTrue, reason: '$name: ${look(preview.first)}');
        expect(pages, isTrue, reason: 'page count');
        expect(layout, isTrue, reason: 'layout per page');
        expect(samePdf, lessThan(0.001), reason: 'same PDF content');
        expect(missing, isEmpty);
      });
    }
  }
}

bool _sameBands(List<Band> x, List<Band> y) =>
    x.length == y.length &&
    [
      for (var i = 0; i < x.length; i++)
        (x[i].top - y[i].top).abs() <= 1.5 &&
            (x[i].thickness - y[i].thickness).abs() <= 1.5,
    ].every((ok) => ok);

String _percent(double share) =>
    '${(share * 100).toStringAsFixed(2)}% of pixels differ';

/// Same bars, rules, photo and name position within 1.5pt: what a page break
/// or a different template would change, and anti-aliasing would not.
bool _sameLayout(TemplateLook a, TemplateLook b) =>
    _sameBands(a.bars, b.bars) &&
    _sameRules(a, b) &&
    (a.nameLeft - b.nameLeft).abs() <= 2;

/// Same rules and photo, and dark bars on both or neither.
bool _sameRules(TemplateLook a, TemplateLook b) =>
    _sameBands(a.rules, b.rules) &&
    a.hasPhoto == b.hasPhoto &&
    a.bars.isEmpty == b.bars.isEmpty;

/// Page 1 of [pdf] drawn by macOS Quick Look at the preview's size.
Uint8List _quickLook(File pdf) {
  final dir = Directory.systemTemp.createTempSync('cv_quicklook');
  try {
    final height = (842 * cvPreviewDpi / 72).round();
    Process.runSync('qlmanage', [
      '-t',
      '-s',
      '$height',
      '-o',
      dir.path,
      pdf.path,
    ]);
    final png = File('${dir.path}/${pdf.uri.pathSegments.last}.png');
    return png.readAsBytesSync();
  } finally {
    dir.deleteSync(recursive: true);
  }
}

String _screenshot(String source, String name) => Directory('$source/templates')
    .listSync()
    .whereType<File>()
    .map((f) => f.path)
    .firstWhere((path) => RegExp('/\\d+-$name-preview\\.png\$').hasMatch(path));

/// The device screenshot and the PDF page next to each other, same height,
/// at half size.
void _sideBySide(Uint8List screenshot, Uint8List page, File to) {
  const height = 877;
  final left = img.copyResize(img.decodePng(screenshot)!, height: height);
  final right = img.copyResize(decodePage(page), height: height);
  const gap = 24;
  final canvas = img.Image(
    width: left.width + gap + right.width,
    height: height,
  )..clear(img.ColorRgb8(200, 200, 200));
  img.compositeImage(canvas, left);
  img.compositeImage(canvas, right, dstX: left.width + gap);
  to.parent.createSync(recursive: true);
  to.writeAsBytesSync(img.encodePng(canvas));
}
